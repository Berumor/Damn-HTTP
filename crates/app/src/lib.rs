//! The Damn HTTP desktop app: a Tauri shell around `damnhttp-core` and
//! `damnhttp-http`.
//!
//! The frontend talks to Rust only through the commands registered in
//! [`bindings`], using the generated `ui/src/bindings.ts`. The webview has
//! no filesystem, shell or network access of its own.

mod commands;
mod dto;
mod error;
mod ops;
mod state;

pub use error::AppError;

use tauri::Manager;
use tauri_specta::{Builder, collect_commands};

use state::AppState;

/// Where the generated TypeScript bindings live, relative to this crate.
#[cfg(test)]
const BINDINGS_PATH: &str = "../../ui/src/bindings.ts";

/// Every command and type the frontend can use. A command also has to be
/// listed in `build.rs` and granted in `capabilities/default.json`.
fn bindings() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new().commands(collect_commands![
        commands::app_info,
        commands::workspace_pick_folder,
        commands::workspace_create,
        commands::workspace_open,
        commands::workspace_close,
        commands::workspace_current,
        commands::workspace_recent,
        commands::workspace_tree,
        commands::collection_create,
        commands::folder_create,
        commands::request_create,
        commands::node_rename,
        commands::node_duplicate,
        commands::node_move,
        commands::node_delete,
    ])
}

#[cfg(test)]
fn typescript() -> specta_typescript::Typescript {
    specta_typescript::Typescript::default()
        .header("// Generated by tauri-specta from the Rust commands. Do not edit.\n// Regenerate with: UPDATE_BINDINGS=1 cargo test -p damnhttp-app bindings\n")
}

/// Starts the app and blocks until it exits.
pub fn run() {
    let bindings = bindings();
    let result = tauri::Builder::default()
        // Used from Rust only (the folder picker). The window's capability
        // grants none of the plugin's own commands.
        .plugin(tauri_plugin_dialog::init())
        .invoke_handler(bindings.invoke_handler())
        .setup(move |app| {
            bindings.mount_events(app);
            app.manage(AppState::new(app.path().app_config_dir()?));
            Ok(())
        })
        .run(tauri::generate_context!());
    if let Err(error) = result {
        // There is no window to show this in; the terminal is all there is.
        #[allow(clippy::print_stderr)]
        {
            eprintln!("Damn HTTP could not start: {error}");
        }
        std::process::exit(1);
    }
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use super::*;

    /// `ui/src/bindings.ts` must match the Rust commands. Run with
    /// `UPDATE_BINDINGS=1` to rewrite the file.
    #[test]
    fn bindings_are_up_to_date() {
        let committed = Path::new(env!("CARGO_MANIFEST_DIR")).join(BINDINGS_PATH);
        let scratch = tempfile::tempdir().unwrap();
        let generated_path = scratch.path().join("bindings.ts");
        bindings().export(typescript(), &generated_path).unwrap();
        let generated = std::fs::read_to_string(&generated_path).unwrap();

        if std::env::var_os("UPDATE_BINDINGS").is_some() {
            std::fs::write(&committed, &generated).unwrap();
            return;
        }
        let existing = std::fs::read_to_string(&committed).unwrap_or_default();
        assert!(
            existing == generated,
            "ui/src/bindings.ts is out of date. Run: UPDATE_BINDINGS=1 cargo test -p damnhttp-app bindings"
        );
    }

    /// The three lists that make a command callable must agree: the
    /// bindings, `build.rs` and the capability file.
    #[test]
    fn every_command_is_declared_and_granted() {
        let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
        let build_script = std::fs::read_to_string(manifest_dir.join("build.rs")).unwrap();
        let capability =
            std::fs::read_to_string(manifest_dir.join("capabilities/default.json")).unwrap();
        for command in commands::NAMES {
            assert!(
                build_script.contains(&format!("\"{command}\"")),
                "`{command}` is missing from COMMANDS in build.rs"
            );
            let permission = format!("\"allow-{}\"", command.replace('_', "-"));
            assert!(
                capability.contains(&permission),
                "{permission} is missing from capabilities/default.json"
            );
        }
        // Nothing but the app's own commands is granted.
        for forbidden in ["core:", "fs:", "dialog:", "shell:", "http:"] {
            assert!(
                !capability.contains(forbidden),
                "{forbidden} must not be granted"
            );
        }
    }
}
